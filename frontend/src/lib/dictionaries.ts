export function getStrings(locale: Locale): Record<StringKey, string> {
  return STRINGS[locale];
}

export function useStrings(): Record<StringKey, string> {
  const locale = useSyncExternalStore(subscribeToLocale, getLocale);
  return STRINGS[locale];
}
